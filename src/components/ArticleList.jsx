import Article from "./Article";

// ArticleList Component
// Renders all articles passed from App.jsx.
// Creates one Article component per post.

function ArticleList({ posts }) {
  return (
    <main>
      {posts.map((post) => (
        <Article
          key={post.id}
          title={post.title}
          date={post.date}
          preview={post.preview}
        />
      ))}
    </main>
  );
}

export default ArticleList;